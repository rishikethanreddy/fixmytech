"""MOCK FlipValue server - for local development and automated tests ONLY.

This is NOT FlipValue. Its numbers come from a fixed toy formula, not market data. Every response is
marked ``"mock": true``, carries an ``X-FlipValue-Mock: true`` header, and says MOCK in ``method`` and
``warnings``. FixMyTech refuses mock responses when configured in live mode.

Run:  python -m fixmytech.integrations.flipvalue.mock_server   (port 8090, key from MOCK_FLIPVALUE_API_KEY)

Failure injection (for testing error paths) via the device model name:
  MOCK-TIMEOUT    sleeps longer than FixMyTech's timeout
  MOCK-503        returns 503
  MOCK-429        returns 429 with Retry-After: 1
  MOCK-UNKNOWN    returns 404 unsupported device
  MOCK-INVALID    returns a body that violates the contract
"""

from __future__ import annotations

import hashlib
import os
import secrets
import time
import uuid
from datetime import UTC, datetime
from typing import Any

from fastapi import FastAPI, Header, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse

from fixmytech.integrations.flipvalue.schemas import ConditionGrade, ValuationRequest

GRADE_FACTOR = {
    ConditionGrade.EXCELLENT: 1.0,
    ConditionGrade.GOOD: 0.85,
    ConditionGrade.FAIR: 0.7,
    ConditionGrade.POOR: 0.5,
    ConditionGrade.FAULTY: 0.35,
}
# Toy multipliers so INR/EUR responses are not absurd in demos. Not exchange rates.
CURRENCY_FACTOR = {"USD": 1.0, "INR": 80.0, "EUR": 0.9, "GBP": 0.8}


def _error(status: int, code: str, message: str, headers: dict[str, str] | None = None) -> JSONResponse:
    return JSONResponse({"error": {"code": code, "message": message, "request_id": str(uuid.uuid4())}},
                        status_code=status, headers={"X-FlipValue-Mock": "true", **(headers or {})})


def create_mock_app(api_key: str | None = None, timeout_sleep_s: float = 12.0) -> FastAPI:
    key = api_key or os.environ.get("MOCK_FLIPVALUE_API_KEY", "mock-dev-key")
    app = FastAPI(title="MOCK FlipValue (development only)", version="1.0-mock")

    @app.exception_handler(RequestValidationError)
    async def _validation(_: Request, exc: RequestValidationError) -> JSONResponse:
        return _error(422, "invalid_request", f"Request does not match contract: {len(exc.errors())} error(s)")

    @app.get("/v1/health")
    def health() -> dict[str, Any]:
        return {"status": "ok", "mock": True}

    @app.post("/v1/valuations")
    def valuations(req: ValuationRequest, x_api_key: str | None = Header(default=None)) -> JSONResponse:
        if not x_api_key or not secrets.compare_digest(x_api_key, key):
            return _error(401, "unauthorized", "Invalid or missing API key")
        model = req.device.model.upper()
        if model == "MOCK-TIMEOUT":
            time.sleep(timeout_sleep_s)
        if model == "MOCK-503":
            return _error(503, "unavailable", "Mock outage")
        if model == "MOCK-429":
            return _error(429, "rate_limited", "Mock rate limit", {"Retry-After": "1"})
        if model == "MOCK-UNKNOWN":
            return _error(404, "unsupported_device", "Device model not in mock catalogue")
        if model == "MOCK-INVALID":
            return JSONResponse({"api_version": "1", "currency": "USD", "mock": True},
                                headers={"X-FlipValue-Mock": "true"})
        if req.currency not in CURRENCY_FACTOR:
            return _error(422, "unsupported_currency", f"Mock supports {sorted(CURRENCY_FACTOR)}")

        # Toy formula: deterministic per model so demos are repeatable.
        seed = int(hashlib.sha256(f"{req.device.manufacturer}|{req.device.model}".lower().encode()).hexdigest(), 16)
        new_price = 300 + seed % 700
        storage = req.device.storage_gb or 128
        age = req.device.age_months if req.device.age_months is not None else 24
        base = new_price * (1 + min(storage, 1024) / 1024 * 0.3) * (0.75 ** (age / 12))
        cf = CURRENCY_FACTOR[req.currency]
        as_is = base * GRADE_FACTOR[req.condition.grade] * cf
        body: dict[str, Any] = {
            "api_version": "1",
            "valuation_id": f"mock-{uuid.uuid4()}",
            "currency": req.currency,
            "as_is": {"value": round(as_is, 2), "low": round(as_is * 0.85, 2), "high": round(as_is * 1.15, 2)},
            "after_repair": None,
            "data_timestamp": datetime.now(UTC).isoformat(),
            "method": "MOCK - deterministic toy formula, not market data",
            "status": "ok",
            "warnings": ["MOCK DATA: generated by the FixMyTech mock FlipValue server, not by FlipValue."],
            "mock": True,
        }
        if req.repair_scenario:
            repaired_grade = ConditionGrade.GOOD if req.condition.grade in (
                ConditionGrade.FAULTY, ConditionGrade.POOR, ConditionGrade.FAIR) else req.condition.grade
            after = base * GRADE_FACTOR[repaired_grade] * cf
            body["after_repair"] = {"value": round(after, 2), "low": round(after * 0.85, 2),
                                    "high": round(after * 1.15, 2)}
        return JSONResponse(body, headers={"X-FlipValue-Mock": "true"})

    return app


app = create_mock_app()

if __name__ == "__main__":
    import uvicorn

    port = int(os.environ.get("MOCK_FLIPVALUE_PORT", "8090"))
    print(f"\n*** MOCK FlipValue server on http://127.0.0.1:{port} - development only, NOT real valuations ***\n")
    uvicorn.run(app, host="127.0.0.1", port=port, log_level="info")
